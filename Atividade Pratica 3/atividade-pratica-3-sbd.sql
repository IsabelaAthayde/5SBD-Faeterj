SELECT C.NOME,
      VD.DT_VENDA,
      VD.VALOR_LIQUIDO,
      ROW_NUMBER() OVER (
          PARTITION BY C.ID_CLIENTE
          ORDER BY VD.DT_VENDA
      ) NUMERO_COMPRA
FROM TB_CLIENTE C
JOIN TB_VENDA VD
ON C.ID_CLIENTE = VD.ID_CLIENTE

---2- 
SELECT VD.NOME,
      SUM(VN.VALOR_LIQUIDO) FATURAMENTO_TOTAL,
      ROUND(
          SUM(VN.VALOR_LIQUIDO) * 100 /
          SUM(SUM(VN.VALOR_LIQUIDO)) OVER (),
          2
      ) PERCENTUAL
FROM TB_VENDA VN
JOIN TB_VENDEDOR VD
ON VN.ID_VENDEDOR = VD.ID_VENDEDOR
WHERE VN.STATUS = 'FECHADA'
GROUP BY VD.NOME

---3- 
WITH VENDAS_MES AS (
   SELECT TRUNC(V.DT_VENDA, 'MM') MES_REFERENCIA,
          VD.NOME,
          SUM(V.VALOR_LIQUIDO) RECEITA_TOTAL
   FROM TB_VENDA V
   JOIN TB_VENDEDOR VD
   ON V.ID_VENDEDOR = VD.ID_VENDEDOR
   GROUP BY TRUNC(V.DT_VENDA, 'MM'), VD.NOME
)
SELECT MES_REFERENCIA,
      NOME,
      RECEITA_TOTAL,
      DENSE_RANK() OVER (
          PARTITION BY MES_REFERENCIA
          ORDER BY RECEITA_TOTAL DESC
      ) POSICAO_RANKING
FROM VENDAS_MES

