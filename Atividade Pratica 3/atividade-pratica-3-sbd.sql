WITH TOTAL_PRODUTOS AS (
   SELECT P.ID_PRODUTO,
          P.NOME,
          SUM(VI.QUANTIDADE) TOTAL_VENDIDO
   FROM TB_VENDA_ITEM VI
   JOIN TB_PRODUTO P
   ON VI.ID_PRODUTO = P.ID_PRODUTO
   GROUP BY P.ID_PRODUTO, P.NOME
), RANKING_PRODUTOS AS (
   SELECT ID_PRODUTO,
          NOME,
          TOTAL_VENDIDO,
          DENSE_RANK() OVER (
              ORDER BY TOTAL_VENDIDO DESC
          ) RANKING
   FROM TOTAL_PRODUTOS
) SELECT ID_PRODUTO,
      NOME,
      TOTAL_VENDIDO
FROM RANKING_PRODUTOS
WHERE RANKING <= 3
